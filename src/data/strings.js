export function t(key, lang, vars = {}) {
  const entry = S[key];
  if (!entry) return key;
  let text = lang === 'ta' ? (entry.ta || entry.en) : entry.en;
  Object.keys(vars).forEach(k => {
    text = text.replace(`{${k}}`, vars[k]);
  });
  return text;
}
